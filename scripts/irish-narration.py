#!/usr/bin/env python3
"""Plan and verify Irish narration offline. This script never calls a provider.

The plan is suitable for an independently coordinated, account-wide guarded
runner. The bundler consumes only existing verified cache receipts; missing or
unknown requests are errors and are never generated by this script.
"""
import argparse
import importlib.util
import json
import math
import subprocess
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parent.parent
LOCALE = 'en-IE'
VOICE = 't6WJWTYTryhcQnrBHdCr'
MODEL = 'eleven_v4'


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


generator = load('irish_generator_base', ROOT / 'scripts/elevenlabs-audio.py')
validator = load('irish_validator_base', ROOT / 'scripts/activate-elevenlabs.py')
SafeError = validator.SafeError


def make_plan():
    texts = validator.catalogue_texts()
    args = SimpleNamespace(model_id=MODEL, voice_id=VOICE, music_seconds=120,
                           sample_only=False, lessons=None, kind='speech', locale='en-GB')
    plan = generator.make_plan(args, texts)
    remapped, requests = {}, {}
    for old_id, old in plan['requests'].items():
        spec = {k: v for k, v in old.items() if k not in ('cacheKey', 'estimatedUsd')}
        identity = generator.sha(generator.canonical(spec))
        remapped[old_id] = identity
        requests[identity] = {**spec, 'cacheKey': identity, 'estimatedUsd': old['estimatedUsd']}
    plan['requests'] = requests
    plan['entries'] = {key: remapped[identity] for key, identity in plan['entries'].items()}
    plan.update(locale=LOCALE, voiceId=VOICE)
    if len(texts) != 1461 or len(plan['entries']) != len(texts):
        raise SafeError('The authored lesson or key coverage changed; review the new catalogue before planning.')
    return plan, texts


def plan_summary(plan):
    credits = sum(len(generator.speech_text(spec)) for spec in plan['requests'].values())
    return {'locale': LOCALE, 'voiceId': VOICE, 'model': MODEL,
            'planHash': generator.sha(generator.canonical(plan)), 'keys': len(plan['entries']),
            'uniqueRequests': len(plan['requests']), 'speechCharacters': plan['speechCharacters'],
            'conservativeCreditsAtOnePerCharacter': credits,
            'reviewStatus': 'native-speaker-and-full-human-listening-pending'}


def write_plan():
    plan, _ = make_plan()
    directory = ROOT / 'media/elevenlabs/irish-plan'
    validator.no_symlinks(directory)
    directory.mkdir(parents=True, exist_ok=True)
    destination = directory / (plan_summary(plan)['planHash'] + '.json')
    if destination.exists() and validator.read_json(destination) != plan:
        raise SafeError('Existing plan conflicts with the canonical plan identity.')
    if not destination.exists():
        generator.write_json(destination, plan)
    return {**plan_summary(plan), 'plan': str(destination)}


def make_bundle():
    plan, _ = make_plan()
    directory = ROOT / 'media/elevenlabs'
    records = {}
    for identity, spec in plan['requests'].items():
        record = generator.cached_record(directory, identity)
        if not record or record.get('status') not in ('received', 'complete'):
            raise SafeError('Missing or unresolved cache receipt; no generation or retry was attempted.')
    for identity, spec in plan['requests'].items():
        # The existing generator only calls the client when no receipt exists.
        # A received response can be normalised locally without a client.
        records[identity] = generator.generate_one(None, directory, spec)
    bundle_json = generator.build_bundle(directory, plan, records)
    return {'bundle': str(bundle_json), **plan_summary(plan)}


_checked_base_request = validator.checked_request

def checked_irish_request(clip, spec, kind):
    settings = clip.get('generationSettings') if isinstance(clip, dict) else None
    payload = spec.get('payload') if isinstance(spec, dict) else None
    if (kind != 'narration' or clip.get('voiceId') != VOICE or clip.get('model') != MODEL
            or not isinstance(settings, dict) or not isinstance(payload, dict)
            or 'language_code' in settings or 'language_code' in payload):
        raise SafeError('Irish speech must use the approved voice and the guarded English dialogue request.')
    _checked_base_request(clip, spec, kind)


def validate_bundle(selected):
    plan, texts = make_plan()
    bundle = validator.bundle_directory(selected)
    if validator.read_json(bundle / 'plan.json') != plan or bundle.name != plan_summary(plan)['planHash']:
        raise SafeError('Bundle does not match the exact current Irish source plan.')
    validator.checked_request = checked_irish_request
    metadata, assets, levels = validator.prepare_bundle(bundle, texts)
    if levels or (bundle / 'music-manifest.json').exists():
        raise SafeError('Irish narration bundle must not contain new music.')
    for source in assets:
        path = bundle / 'assets' / source.lstrip('/')
        try:
            subprocess.run(['ffmpeg', '-nostdin', '-v', 'error', '-xerror', '-protocol_whitelist', 'file,pipe',
                            '-i', str(path), '-f', 'null', '-'], check=True,
                           stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, timeout=90)
        except (OSError, subprocess.SubprocessError):
            raise SafeError('A staged MP3 failed full decode.') from None
    manifest = metadata['src/narration-manifest.json']
    manifest['validatedAt'] = manifest.pop('activatedAt')
    clips = manifest['clips']
    lessons = sorted({key.split('/')[0] for key in texts if key != 'sample'})
    if len(lessons) != 30:
        raise SafeError('The complete thirty-lesson coverage is required.')
    manifest.update(locale=LOCALE, selectedVoiceId=VOICE, coveredLessons=lessons,
                    partialCatalogue=False, reviewStatus='full-catalogue-review-pending',
                    review={'operatorConfirmedReviewed': False, 'nativeSpeakerReview': 'pending',
                            'fullHumanListeningReview': 'pending',
                            'automatedChecks': ['exact current authored English text and key coverage',
                              'plan, request and cache receipt identities', 'audio hashes, encoding, durations and full decode']})
    return {
        'narration-index.en-IE.json': metadata['src/narration-index.json'],
        'narration-durations.en-IE.json': {k: math.floor(v['duration'] * 1000 + 0.5) for k, v in clips.items()},
        'narration-manifest.en-IE.json': manifest,
        'narration-availability.en-IE.json': {'schemaVersion': 1, 'locale': LOCALE, 'lessons': lessons},
    }, assets


def stage_metadata(selected):
    metadata, assets = validate_bundle(selected)
    plan_hash = metadata['narration-manifest.en-IE.json']['sourcePlanHash']
    destination = ROOT / 'media/elevenlabs/irish-validated' / plan_hash
    validator.no_symlinks(destination)
    if destination.exists():
        raise SafeError('Validated metadata destination already exists; inspect it before proceeding.')
    destination.mkdir(parents=True, mode=0o700)
    for name, value in metadata.items():
        validator.atomic_write(destination / name, validator.json_bytes(value), 0o600)
    return {'status': 'validated-staged-only', 'metadata': str(destination), 'uniqueAssets': len(assets),
            'reviewStatus': 'native-speaker-and-full-human-listening-pending'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['plan', 'bundle', 'validate'])
    parser.add_argument('--bundle')
    args = parser.parse_args()
    if (args.action == 'validate') != bool(args.bundle):
        parser.error('Only validate requires --bundle.')
    result = write_plan() if args.action == 'plan' else make_bundle() if args.action == 'bundle' else stage_metadata(args.bundle)
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    try:
        main()
    except (SafeError, generator.SafeError, OSError, ValueError) as error:
        print(f'Error: {error}', file=__import__('sys').stderr)
        raise SystemExit(1)
